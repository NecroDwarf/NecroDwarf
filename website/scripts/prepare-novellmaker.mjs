import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { format } from "prettier";
import {
  compile,
  commit,
  repository,
  docPath,
} from "./novellmaker-reference.mjs";
const root = "src/app/projects/novellmaker/docs";
const generated = async (path, content, parser = "json") =>
  writeFile(path, await format(content, { parser }));
await mkdir(`${root}/data`, { recursive: true });
await mkdir(`${root}/articles`, { recursive: true });
const metadata = [],
  search = [],
  manifest = { commit, repository, documents: [] };
const files = (await readdir(`${root}/source`))
  .filter((f) => f.endsWith(".md"))
  .sort();
if (files.length !== 22)
  throw new Error(`Expected 22 documents, got ${files.length}`);
for (const file of files) {
  const source = await readFile(`${root}/source/${file}`, "utf8"),
    slug = file.slice(0, -3),
    path = docPath(slug);
  const article = compile(source, file);
  metadata.push([slug, article.title]);
  search.push({
    title: article.title,
    href: path,
    description: "Документ NovellMaker",
  });
  for (const h of article.headings.slice(1)) {
    const marker = source.indexOf(`${"#".repeat(h.level)} ${h.title}`);
    const description =
      marker < 0
        ? article.title
        : (source
            .slice(marker + h.title.length + h.level + 2)
            .split(/\n\s*\n/)
            .find((s) => s.trim() && !s.startsWith("<a "))
            ?.replace(/[`*#]/g, "")
            .slice(0, 200) ?? article.title);
    search.push({ title: h.title, href: `${path}#${h.id}`, description });
  }
  manifest.documents.push({
    file,
    path,
    sha256: createHash("sha256").update(source).digest("hex"),
    ids: article.ids,
    links: article.links,
    codes: article.codes,
  });
  await generated(
    `${root}/data/${slug}.json`,
    JSON.stringify({
      title: article.title,
      headings: article.headings,
      nodes: article.nodes,
    }),
  );
  await generated(
    `${root}/articles/${slug}.tsx`,
    `// Generated by npm run docs:novellmaker.\nimport article from "../data/${slug}.json";\nimport { DocArticle } from "../ui/DocArticle";\nexport default function Article() { return <DocArticle article={article} />; }\n`,
    "typescript",
  );
}
await generated(`${root}/metadata.json`, JSON.stringify(metadata));
await generated(
  `${root}/route-slugs.json`,
  JSON.stringify(metadata.map(([slug]) => slug)),
);
await generated(`${root}/search-index.json`, JSON.stringify(search));
await mkdir("build", { recursive: true });
await writeFile(
  "build/novellmaker-manifest.json",
  JSON.stringify(manifest) + "\n",
);
console.log(
  `NovellMaker: prepared ${files.length} articles, ${search.length} search entries`,
);
